#!/usr/bin/env node
// Embed the maintained hardening source and regenerate the standalone script CSP hash.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = join(root, 'index.html');
let html = readFileSync(file, 'utf8');
for (const [type, path] of [['JS','src/business.js'], ['CSS','src/business.css']]) {
  const pattern = new RegExp(`/\\* BUSINESS_${type}_START \\*/[\\s\\S]*?/\\* BUSINESS_${type}_END \\*/`);
  if (!pattern.test(html)) throw new Error('Missing business embed markers: ' + type);
  const block = `/* BUSINESS_${type}_START */\n${readFileSync(join(root,path),'utf8')}\n/* BUSINESS_${type}_END */`;
  html = html.replace(pattern, () => block);
}
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m => "'sha256-" + createHash('sha256').update(m[1]).digest('base64') + "'");
const csp = `default-src 'none'; script-src 'self' ${scripts.join(' ')} 'wasm-unsafe-eval' blob: https://cdn.jsdelivr.net; worker-src 'self' blob:; style-src 'self' 'unsafe-inline'; font-src 'self'; img-src 'self' data: blob:; connect-src 'self' blob: https://cdn.jsdelivr.net https://extensions.duckdb.org; base-uri 'none'; form-action 'none'; object-src 'none'`;
html = html.replace(/(<meta http-equiv="Content-Security-Policy" content=")[^"]*(">)/, (_,a,b) => a + csp + b);
html = html.replace(/<!-- Defence in depth\.[\s\S]*?-->/, '<!-- Script hashes are generated by scripts/build-business.mjs. The bundled server adds frame protection and other HTTP headers. -->');
writeFileSync(file,html);
console.log('Embedded business sources and updated script hashes.');
